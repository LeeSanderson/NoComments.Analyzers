using NoComments.Analyzers.Tests.Helpers;
using Shouldly;

namespace NoComments.Analyzers.Tests;

public class NonCommentShould(PackageFixture fixture, ITestOutputHelper testOutputHelper)
    : NoCommentsTestBase(fixture, testOutputHelper)
{
    [Fact]
    public async Task NotReportDirectivesOrDisabledText()
    {
        using var project = await CreateProjectBuilderAsync();
        await project.AddFileAsync(
            "Program.cs",
            """
            #nullable enable
            #region Setup
            #pragma warning disable CS0168
            int unused;
            #pragma warning restore CS0168
            #endregion
            #if NEVER_DEFINED
            this is disabled text // with what looks like a comment
            /* and this */
            #endif
            return;

            """);

        var buildOutput = await project.BuildAndGetOutputAsync();

        buildOutput.DiagnosticsIn("Program.cs").ShouldBeEmpty();
    }

    [Fact]
    public async Task NotReportAShebangInAFileBasedProgram()
    {
        using var project = await CreateProjectBuilderAsync([("Features", "$(Features);FileBasedProgram")]);
        await project.AddFileAsync(
            "Program.cs",
            """
            #!/usr/bin/env dotnet
            return;

            """);

        var buildOutput = await project.BuildAndGetOutputAsync();

        buildOutput.DiagnosticsIn("Program.cs").ShouldBeEmpty();
    }

    [Fact]
    public async Task NotReportCommentsInAFileWithAnAutoGeneratedHeader()
    {
        using var project = await CreateProjectBuilderAsync([("GenerateDocumentationFile", "true")]);
        await project.AddFileAsync("Program.cs", "return;\n");
        await project.AddFileAsync(
            "Generated.cs",
            """
            // <auto-generated/>
            /* multi-line */

            /// <summary>A widget.</summary>
            internal sealed class Widget
            {
                // single-line
            }

            """);

        var buildOutput = await project.BuildAndGetOutputAsync();

        buildOutput.DiagnosticsIn("Generated.cs").ShouldBeEmpty();
    }

    [Fact]
    public async Task NotReportCommentsInAFileWithAGeneratedFileName()
    {
        using var project = await CreateProjectBuilderAsync();
        await project.AddFileAsync("Program.cs", "return;\n");
        await project.AddFileAsync(
            "Widget.g.cs",
            """
            internal sealed class Widget
            {
                // single-line
                /* multi-line */
            }

            """);

        var buildOutput = await project.BuildAndGetOutputAsync();

        buildOutput.DiagnosticsIn("Widget.g.cs").ShouldBeEmpty();
    }
}
